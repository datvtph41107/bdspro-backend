// SeoSearchPerformanceDaily stores search-result performance for a URL/query/day.
//
// Business meaning:
//   - This is the backend evidence layer for impression, click, CTR and average
//     position.
//   - In mock mode, rows are generated by the backend so admin can understand the
//     full SEO loop before Google Search Console is integrated.
//   - In real mode, the same table receives rows from Google Search Console.
type SeoSearchPerformanceDaily struct {
	ID           uint64    `gorm:"primaryKey;autoIncrement"`
	SeoDomainID  *uint64   `gorm:"column:seo_domain_id;index"`
	CanonicalURL string    `gorm:"column:canonical_url;type:text;not null;index"`
	Query        string    `gorm:"column:query;type:text;not null;default:'';index"`
	Device       string    `gorm:"column:device;type:varchar(32);not null;default:'';index"`
	Country      string    `gorm:"column:country;type:varchar(16);not null;default:'';index"`
	SearchType   string    `gorm:"column:search_type;type:varchar(32);not null;default:'web';index"`
	Date         time.Time `gorm:"column:date;type:date;not null;index"`
	Clicks       float64   `gorm:"column:clicks;not null;default:0"`
	Impressions  float64   `gorm:"column:impressions;not null;default:0"`
	CTR          float64   `gorm:"column:ctr;not null;default:0"`
	Position     float64   `gorm:"column:position;not null;default:0"`
	DataSource   string    `gorm:"column:data_source;type:varchar(32);not null;default:'mock';index"`
	SourceRunID  *uint64   `gorm:"column:source_run_id;index"`
	ImportedAt   time.Time `gorm:"column:imported_at;not null;autoCreateTime"`
	CreatedAt    time.Time `gorm:"column:created_at;autoCreateTime"`
	UpdatedAt    time.Time `gorm:"column:updated_at;autoUpdateTime"`
}

func (SeoSearchPerformanceDaily) TableName() string { return "seo_search_performance_daily" }

